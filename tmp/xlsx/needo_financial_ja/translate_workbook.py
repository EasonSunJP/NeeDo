def translate_text(text: str) -> str:
    if not text or re.fullmatch(r"https?://\S+", text.strip()):
        return text
    if text in EXACT:
        return EXACT[text]
    result = text
    for old, new in sorted(SENTENCE_REPLACEMENTS.items(), key=lambda item: len(item[0]), reverse=True):
        result = result.replace(old, new)
    for old, new in sorted(PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
        result = result.replace(old, new)
    for old, new in sorted(FINAL_REPLACEMENTS.items(), key=lambda item: len(item[0]), reverse=True):
        result = result.replace(old, new)
    result = result.replace("，", "、").replace("；", "。")
    # Some cleanup keys intentionally match the punctuation-normalized form.
    for old, new in sorted(FINAL_REPLACEMENTS.items(), key=lambda item: len(item[0]), reverse=True):
        result = result.replace(old, new)
    result = result.replace("（", "（").replace("）", "）")
    result = result.replace("×", "×")
    return result


def replace_sheet_names_in_xml(data: bytes) -> bytes:
    text = data.decode("utf-8")
    for source, target in SHEET_NAMES.items():
        text = text.replace(source, target)
    text = text.replace("zh-CN", "ja-JP")
    # Use a CJK font available by default on macOS.  It includes Japanese kana
    # and avoids relying on a Windows-only Meiryo installation.
    text = text.replace("Meiryo", "Hiragino Sans GB")
    text = text.replace('<a:ea typeface="Calibri Light"/>', '<a:ea typeface="Hiragino Sans GB"/>')
    text = text.replace('<a:ea typeface="Calibri"/>', '<a:ea typeface="Hiragino Sans GB"/>')
    return text.encode("utf-8")


def translate_shared_strings(data: bytes) -> tuple[bytes, list[tuple[str, str]]]:
    root = ET.fromstring(data)
    changes: list[tuple[str, str]] = []
    for si in root.findall(f"{{{NS_MAIN}}}si"):
        nodes = si.findall(f".//{{{NS_MAIN}}}t")
        original = "".join(node.text or "" for node in nodes)
        translated = translate_text(original)
        if translated != original:
            changes.append((original, translated))
        # Rich-text runs in the source are font-fallback fragments rather than
        # semantic styling.  One plain shared string lets the existing cell
        # style select the Japanese font consistently.
        for child in list(si):
            si.remove(child)
        t = ET.SubElement(si, f"{{{NS_MAIN}}}t")
        if translated[:1].isspace() or translated[-1:].isspace():
            t.set(f"{{{NS_XML}}}space", "preserve")
        t.text = translated
    return ET.tostring(root, encoding="utf-8", xml_declaration=True), changes


def translate_text_nodes(data: bytes) -> bytes:
    try:
        root = ET.fromstring(data)
    except ET.ParseError:
        return replace_sheet_names_in_xml(data)
    changed = False
    for node in root.iter():
        local_name = node.tag.rsplit("}", 1)[-1]
        if local_name in {"t", "v", "text", "lpstr"} and node.text:
            new_value = translate_text(node.text)
            if new_value != node.text:
                node.text = new_value
                changed = True
    output = ET.tostring(root, encoding="utf-8", xml_declaration=True) if changed else data
    return replace_sheet_names_in_xml(output)


def build() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="needo-ja-") as tmp:
        temp_output = Path(tmp) / OUTPUT.name
        changes: list[tuple[str, str]] = []
        with zipfile.ZipFile(SOURCE, "r") as src, zipfile.ZipFile(temp_output, "w") as dst:
            for info in src.infolist():
                data = src.read(info.filename)
                if info.filename == "xl/sharedStrings.xml":
                    data, shared_changes = translate_shared_strings(data)
                    changes.extend(shared_changes)
                elif info.filename.endswith((".xml", ".vml")):
                    data = translate_text_nodes(data)
                dst.writestr(info, data)
        shutil.copy2(temp_output, OUTPUT)

    audit = OUTPUT.with_suffix(".translation_audit.tsv")
    with audit.open("w", encoding="utf-8") as handle:
        handle.write("source\tja\n")
        for source, target in changes:
            handle.write(source.replace("\t", " ").replace("\n", " ") + "\t" + target.replace("\t", " ").replace("\n", " ") + "\n")
    print(f"OUTPUT={OUTPUT}")
    print(f"TRANSLATED_SHARED_STRINGS={len(changes)}")
    print(f"AUDIT={audit}")


if __name__ == "__main__":
    build()
