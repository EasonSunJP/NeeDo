function NoticeBlockPreview({ block }: { block: OfficialNoticeBlock }) {
  if (block.type === "divider") {
    return <div className="border-t border-[color:color-mix(in_srgb,var(--admin-line)_38%,transparent)]" />;
  }

  if (block.type === "image") {
    return (
      <figure className="overflow-hidden rounded-lg border border-line bg-white">
        {block.content.trim() ? (
          <img alt={block.caption || "官方通知图片"} className="max-h-80 w-full object-cover" src={block.content} />
        ) : (
          <div className="grid h-40 place-items-center bg-paper text-sm font-bold text-ink/45">图片地址未填写</div>
        )}
        {block.caption ? <figcaption className="border-t border-line px-4 py-3 text-sm font-bold text-ink/55">{block.caption}</figcaption> : null}
      </figure>
    );
  }

  if (block.type === "video") {
    return (
      <figure className="overflow-hidden rounded-lg border border-line bg-ink text-white">
        {block.content.trim() ? (
          <video className="max-h-80 w-full bg-black" controls src={block.content} />
        ) : (
          <div className="grid h-40 place-items-center text-sm font-bold text-white/65">视频地址未填写</div>
        )}
        {block.caption ? <figcaption className="border-t border-white/10 px-4 py-3 text-sm font-bold text-white/70">{block.caption}</figcaption> : null}
      </figure>
    );
  }

  if (block.type === "file") {
    const fileLabel = block.caption || block.fileName || "下载附件";

    return (
      <a
        className="flex items-center justify-between gap-3 rounded-lg border border-line bg-white px-4 py-3 text-sm font-black text-ink transition hover:border-moss hover:text-moss"
        download={block.fileName || undefined}
        href={block.content || "#"}
      >
        <span className="min-w-0">
          <span className="block truncate">{fileLabel}</span>
          {block.fileSize ? <span className="mt-1 block text-xs font-bold text-ink/45">{Math.max(1, Math.round(block.fileSize / 1024))}KB</span> : null}
        </span>
        <span className="shrink-0 rounded-md bg-paper px-3 py-2 text-xs">下载</span>
      </a>
    );
  }

  if (block.type === "heading") {
    return <h3 className="text-xl font-black text-ink">{block.content}</h3>;
  }

  if (block.type === "subheading") {
    return <h4 className="text-base font-black text-ink/80">{block.content}</h4>;
  }

  if (block.type === "bullet") {
    return <p className="pl-4 text-sm leading-7 text-ink/70 before:mr-2 before:content-['•']">{block.content}</p>;
  }

  if (block.type === "numbered") {
    return <p className="rounded-md border-l-4 border-moss bg-white px-4 py-3 text-sm leading-7 text-ink/70">{block.content}</p>;
  }

  if (block.type === "quote") {
    return <blockquote className="border-l-4 border-ink/20 bg-white px-4 py-3 text-sm font-semibold leading-7 text-ink/70">{block.content}</blockquote>;
  }

  if (block.type === "callout") {
    return <p className="rounded-lg border border-lemon/50 bg-lemon/15 px-4 py-3 text-sm font-bold leading-7 text-ink/75">{block.content}</p>;
  }

  return <p className="text-sm leading-7 text-ink/70">{block.content}</p>;
}

